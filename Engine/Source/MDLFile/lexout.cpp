mdl_scan::mdl_scan(const char *in, int sz)
{
	size = sz;
	mdltext = new char[sz+1];
	state = new mdl_state_t[sz+1];
	if (mdltext == NULL
	  || state == NULL) {
		mdlerror("No space for scanner!");
		exit(1);
	}
	mustfree = 1;
	mdl_end = 0;
	mdl_start = 0;
	mdl_lastc = YYNEWLINE;
	mdlin = in;
	mdlout = stdout;
	mdllineno = 1;
	mdlleng = 0;
}

mdl_scan::~mdl_scan()
{
	if (mustfree) {
		mustfree = 0;
		delete[] mdltext;
		delete[] state;
	}
}

void
mdl_scan::mdlerror(char *fmt, ...)
{
	va_list va;

	va_start(va, fmt);
	if (mdllineno)
		fprintf(stderr, "%d: ", mdllineno);
	(void) vfprintf(stderr, fmt, va);
	fputc('\n', stderr);
	va_end(va);
}

