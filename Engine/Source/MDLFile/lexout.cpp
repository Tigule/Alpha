void
mdl_scan::mdl_reset()
{
	YY_INIT();
	mdllineno = 1;
}

int
mdl_scan::input()
{
	int c;
	if (mdl_end > mdlleng) {
		mdl_end--;
		memmove(mdltext+mdlleng, mdltext+mdlleng+1,
			(size_t) (mdl_end-mdlleng));
		c = save;
		YY_USER();
	} else
		c = mdlgetc();
	mdl_lastc = c;
	if (c == YYNEWLINE)
		mdllineno++;
	return c;
}

int
mdl_scan::unput(int c)
{
	if (mdl_end >= size) {
		YY_FATAL("Push-back buffer overflow");
	} else {
		if (mdl_end > mdlleng) {
			mdltext[mdlleng] = save;
			memmove(mdltext+mdlleng+1, mdltext+mdlleng,
				(size_t) (mdl_end-mdlleng));
			mdltext[mdlleng] = 0;
		}
		mdl_end++;
		save = c;
		if (c == YYNEWLINE)
			mdllineno--;
	}
	return c;
}

void
mdl_scan::mdlcomment(char *const mat)
{
	register int c;
	register const char *cp;

	for (cp = mat; *cp != 0; ) {
		c = input();
		if (c == 0) {
			mdlerror("end of file in comment");
			break;
		}
		if (c != *cp++) {
			cp = mat;
			if (c == *cp)
				cp++;
		}
	}
}
