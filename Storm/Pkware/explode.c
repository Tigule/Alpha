#define EXP_INBUF_SIZE  0x800
#define EXP_HISTORY     0x1000
#define EXP_OUTBUF_SIZE (2 * EXP_HISTORY)
#define EXP_END_LENGTH  517

typedef struct {
  unsigned int(__cdecl *read_buf)(char *buf, unsigned int *size, void *param);
  void(__cdecl *write_buf)(char *buf, unsigned int *size, void *param);
  void         *param;
  unsigned int  ctype;
  unsigned int  dsize_bits;
  unsigned long bit_buf;
  unsigned int  bit_count;
  unsigned int  in_pos;
  unsigned int  in_bytes;
  unsigned int  out_pos;
  unsigned long total;
  unsigned char in_buf[EXP_INBUF_SIZE];
  unsigned char out_buf[EXP_OUTBUF_SIZE];
} EXPLODE_WORK;

