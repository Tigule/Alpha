/* next input byte, or -1 at the end of the input */
static int ReadByte(EXPLODE_WORK *work) {
  if (work->in_pos == work->in_bytes) {
    unsigned int size = EXP_INBUF_SIZE;
    unsigned int got = work->read_buf((char *)work->in_buf, &size, work->param);
    if (!got) {
      return -1;
    }
    work->in_bytes = got;
    work->in_pos = 0;
  }
  return work->in_buf[work->in_pos++];
}

/* make at least `count` bits available; returns 0 if the input ends first */
static int FillBits(EXPLODE_WORK *work, unsigned int count) {
  while (work->bit_count < count) {
    int byte = ReadByte(work);
    if (byte < 0) {
      return 0;
    }
    work->bit_buf |= (unsigned long)byte << work->bit_count;
    work->bit_count += 8;
  }
  return 1;
}

static int WasteBits(EXPLODE_WORK *work, unsigned int count, unsigned int *value) {
  if (!FillBits(work, count)) {
    return 0;
  }
  *value = (unsigned int)(work->bit_buf & ((1UL << count) - 1));
  work->bit_buf >>= count;
  work->bit_count -= count;
  return 1;
}

/* decode one symbol of a prefix code given as (bit length, code) pairs, least significant bit first */
static int DecodeSymbol(EXPLODE_WORK *work, const unsigned char *bits, const unsigned short *codes16, const unsigned char *codes8,
                        unsigned int count, unsigned int *symbol) {
  unsigned int i;

  FillBits(work, 16); /* near the end of the stream fewer bits may remain; matching below checks bit_count */
  for (i = 0; i < count; ++i) {
    unsigned int  length = bits[i];
    unsigned long code = codes16 ? codes16[i] : codes8[i];
    if (length <= work->bit_count && (work->bit_buf & ((1UL << length) - 1)) == code) {
      work->bit_buf >>= length;
      work->bit_count -= length;
      *symbol = i;
      return 1;
    }
  }
  return 0;
}

static void FlushHistory(EXPLODE_WORK *work) {
  unsigned int size = EXP_HISTORY;
  work->write_buf((char *)work->out_buf, &size, work->param);
  memmove(work->out_buf, work->out_buf + EXP_HISTORY, EXP_HISTORY);
  work->out_pos -= EXP_HISTORY;
}

static void PutByte(EXPLODE_WORK *work, unsigned char byte) {
  work->out_buf[work->out_pos++] = byte;
  ++work->total;
  if (work->out_pos == EXP_OUTBUF_SIZE) {
    FlushHistory(work);
  }
}

static int DecodeLit(EXPLODE_WORK *work, unsigned int *literal) {
  if (work->ctype == CMP_BINARY) {
    return WasteBits(work, 8, literal);
  }
  return DecodeSymbol(work, ChBitsAsc, ChCodeAsc, 0, 256, literal);
}

static int DecodeDist(EXPLODE_WORK *work, unsigned int copy, unsigned int *distance) {
  unsigned int symbol;
  unsigned int low;
  unsigned int lowbits = (copy == 2) ? 2 : work->dsize_bits;

  if (!DecodeSymbol(work, DistBits, 0, DistCode, 64, &symbol) || !WasteBits(work, lowbits, &low)) {
    return 0;
  }
  *distance = ((symbol << lowbits) | low) + 1;
  return 1;
}

static unsigned int Expand(EXPLODE_WORK *work) {
  for (;;) {
    unsigned int flag;
    if (!WasteBits(work, 1, &flag)) {
      return CMP_BAD_DATA;
    }

    if (!flag) {
      unsigned int literal;
      if (!DecodeLit(work, &literal)) {
        return CMP_BAD_DATA;
      }
      PutByte(work, (unsigned char)literal);
    } else {
      unsigned int symbol;
      unsigned int extra = 0;
      unsigned int length;
      unsigned int copy;
      unsigned int distance;

      if (!DecodeSymbol(work, LenBits, 0, LenCode, 16, &symbol)) {
        return CMP_BAD_DATA;
      }
      if (ExLenBits[symbol] && !WasteBits(work, ExLenBits[symbol], &extra)) {
        return CMP_BAD_DATA;
      }
      length = LenBase[symbol] + extra;
      if (length == EXP_END_LENGTH) {
        return CMP_NO_ERROR;
      }

      copy = length + 2;
      if (!DecodeDist(work, copy, &distance) || distance > work->total) {
        return CMP_BAD_DATA;
      }
      /* byte by byte: the source may overlap the bytes being written; out_pos never drops below EXP_HISTORY once
         that much has been written, so the source is always inside the buffer */
      while (copy--) {
        PutByte(work, work->out_buf[work->out_pos - distance]);
      }
    }
  }
}

unsigned int __cdecl explode(
    unsigned int(__cdecl *read_buf)(char *buf, unsigned int *size, void *param),
    void(__cdecl *write_buf)(char *buf, unsigned int *size, void *param),
    char *work_buf,
    void *param
) {
  EXPLODE_WORK *work = (EXPLODE_WORK *)work_buf;
  int           ctype;
  int           dsize_bits;
  unsigned int  result;

  work->read_buf = read_buf;
  work->write_buf = write_buf;
  work->param = param;
  work->bit_buf = 0;
  work->bit_count = 0;
  work->in_pos = 0;
  work->in_bytes = 0;
  work->out_pos = 0;
  work->total = 0;

  ctype = ReadByte(work);
  dsize_bits = ReadByte(work);
  if (ctype < 0 || dsize_bits < 0) {
    return CMP_BAD_DATA;
  }
  if (ctype != CMP_BINARY && ctype != CMP_ASCII) {
    return CMP_INVALID_MODE;
  }
  if (dsize_bits < 4 || dsize_bits > 6) {
    return CMP_INVALID_DICTSIZE;
  }
  work->ctype = (unsigned int)ctype;
  work->dsize_bits = (unsigned int)dsize_bits;

  result = Expand(work);
  if (work->out_pos) {
    unsigned int size = work->out_pos;
    work->write_buf((char *)work->out_buf, &size, work->param);
  }
  return result;
}
